"""Generates cpp/src/recognizer_bidi.inc: UAX #9 bidi classes (Python unicodedata), Bidi_Mirroring_Glyph
(BidiMirroring.txt) and Bidi_Paired_Bracket(_Type) (BidiBrackets.txt) of the same Unicode version.

usage: gen_bidi_tables.py BidiMirroring.txt BidiBrackets.txt > cpp/src/recognizer_bidi.inc
"""
import sys
import unicodedata

ver = unicodedata.unidata_version


def pairs(path, fields):
    out = []
    for line in open(path, encoding='utf-8'):
        line = line.split('#')[0].strip()
        if not line:
            continue
        p = [x.strip() for x in line.split(';')]
        out.append(tuple(p[:fields]))
    return out


ranges = []
for cp in range(0x110000):
    c = unicodedata.bidirectional(chr(cp)) or 'L'
    if c == 'L':
        continue
    if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == c:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, c])

print(f'// Generated by tools/gen_bidi_tables.py from Unicode {ver}: bidi classes (UAX #9) of every code point that')
print('// is not L, as ranges [first, last, class] sorted by code point; Bidi_Mirroring_Glyph and Bidi_Paired_Bracket')
print('// pairs [code point, other] sorted by code point (brackets: [code point, pair, 1 = open]).')
print('static constexpr uint32_t kBidiClass[][3] = {')
row = []
for a, b, c in ranges:
    row.append(f'{{0x{a:X}, 0x{b:X}, k{c}}}')
    if len(row) == 5:
        print('    ' + ', '.join(row) + ',')
        row = []
if row:
    print('    ' + ', '.join(row) + ',')
print('};')
for name, path, n in (('kBidiMirror', sys.argv[1], 2), ('kBidiBracket', sys.argv[2], 3)):
    rows = pairs(path, n)
    print(f'static constexpr uint32_t {name}[][{n}] = {{')
    cells = []
    for r in rows:
        v = [f'0x{int(r[0], 16):X}', f'0x{int(r[1], 16):X}'] + (['1' if r[2] == 'o' else '0'] if n == 3 else [])
        cells.append('{' + ', '.join(v) + '}')
    for i in range(0, len(cells), 6):
        print('    ' + ', '.join(cells[i:i + 6]) + ',')
    print('};')
