"""Generate cpp/src/recognizer_langcode.inc from a trace/likely_script_dump.py dump of the original's
aksara::script_util::MostLikelyScript (i18n_identifiers language-code validation and likely-script data).

usage: gen_likely_scripts.py DUMPDIR > cpp/src/recognizer_langcode.inc
"""
import os, sys

d = sys.argv[1]
names = {int(l.split()[0]): l.split()[1] for l in open(os.path.join(d, 'names.txt'))}
def load(f):
    out = []
    for l in open(os.path.join(d, f + '.txt')):
        t, c = l.rstrip('\n').rsplit(' ', 1)
        out.append((t, names[int(c)]))
    return out
lang = dict(load('lang'))
arab = dict(load('arab'))
valid = sorted(l for l in lang if l and arab[l + '-Arab'] == 'Arab')
region = load('region')
ja = {t.split('-', 1)[1]: s for t, s in region if t.startswith('ja-')}
regions = sorted(r for r, s in ja.items() if s != 'Latn')
overrides = sorted((t, s) for t, s in region if t.split('-', 1)[1] in ja and ja[t.split('-', 1)[1]] != 'Latn'
                   and s != lang[t.split('-', 1)[0]])
script_tags = dict(load('script'))
scripts = sorted(s for s in set(names.values()) if script_tags.get('und-' + s) == s)

def bits(codes, alphabet_len, width):
    n = alphabet_len ** width
    words = [0] * ((n + 63) // 64)
    for c in codes:
        i = 0
        for ch in c: i = i * 26 + (ord(ch) - 97)
        words[i // 64] |= 1 << (i % 64)
    return words

def emit_words(name, words):
    print('constexpr uint64_t %s[] = {' % name)
    for i in range(0, len(words), 4):
        print('    ' + ', '.join('0x%016xull' % w for w in words[i:i + 4]) + ',')
    print('};')

print('// Generated by trace/gen_likely_scripts.py from the original\'s aksara::script_util::MostLikelyScript')
print('// (i18n_identifiers data, read with trace/likely_script_dump.py). Do not edit.')
print('// Language codes that parse: bit (c0*26 + c1) of kValidLang2, (c0*676 + c1*26 + c2) of kValidLang3.')
emit_words('kValidLang2', bits([l for l in valid if len(l) == 2], 26, 2))
emit_words('kValidLang3', bits([l for l in valid if len(l) == 3], 26, 3))
print('// Likely script of a valid language code when it is not Latn.')
print('constexpr std::pair<std::string_view, std::string_view> kLikelyScripts[] = {')
items = [(l, lang[l]) for l in valid if lang[l] != 'Latn']
for i in range(0, len(items), 6):
    print('    ' + ' '.join('{"%s", "%s"},' % kv for kv in items[i:i + 6]))
print('};')
print('// Region subtags that parse.')
print('constexpr std::string_view kRegions[] = {')
for i in range(0, len(regions), 16):
    print('    ' + ' '.join('"%s",' % r for r in regions[i:i + 16]))
print('};')
print('// Language-region pairs whose likely script differs from the language\'s.')
print('constexpr std::pair<std::string_view, std::string_view> kRegionScripts[] = {')
for i in range(0, len(overrides), 5):
    print('    ' + ' '.join('{"%s", "%s"},' % kv for kv in overrides[i:i + 5]))
print('};')
print('// Script subtags that parse (ISO 15924 codes known to ScriptCodeConverter).')
print('constexpr std::string_view kScriptCodes[] = {')
for i in range(0, len(scripts), 16):
    print('    ' + ' '.join('"%s",' % s for s in scripts[i:i + 16]))
print('};')
v2 = dict(load('variants2'))
variants = sorted(t[3:] for t, sc in v2.items() if t.startswith('ru-') and t.count('-') == 1 and sc == 'Cyrl'
                  and t != 'ru-x-petr1708')
grandfathered = sorted((t.lower(), sc) for t, sc in v2.items() if t.split('-')[0] in ('art', 'cel', 'en', 'i', 'no', 'sgn', 'zh')
                       and not t.endswith(('-TW', '-Cyrl')) and not t.startswith('zh-Hant-'))
print('// Variant subtags that parse (registered ones known to the converter).')
print('constexpr std::string_view kVariants[] = {')
for i in range(0, len(variants), 10):
    print('    ' + ' '.join('"%s",' % v for v in variants[i:i + 10]))
print('};')
print('// BCP 47 grandfathered tags (lowercase) and their likely script; with any further subtag they do not parse.')
print('constexpr std::pair<std::string_view, std::string_view> kGrandfathered[] = {')
for i in range(0, len(grandfathered), 5):
    print('    ' + ' '.join('{"%s", "%s"},' % kv for kv in grandfathered[i:i + 5]))
print('};')
extlangs = sorted(t[:-5] for t, sc in load('extlang') if sc == 'Cyrl')
print('// Extended language subtags that parse, as "<language>-<extlang>" (zh-yue is yue).')
print('constexpr std::string_view kExtlangs[] = {')
for i in range(0, len(extlangs), 10):
    print('    ' + ' '.join('"%s",' % v for v in extlangs[i:i + 10]))
print('};')
sys.stderr.write('valid %d likely %d regions %d overrides %d scripts %d variants %d grandfathered %d extlangs %d\n' % (
    len(valid), len(items), len(regions), len(overrides), len(scripts), len(variants), len(grandfathered), len(extlangs)))
